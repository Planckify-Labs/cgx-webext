//! Human- and machine-readable renderings of coverage data.

use crate::analyze::{Report, Support, Verdict};
use crate::registry::{Engine, Registry, StatusCounts};
use serde_json::{Value, json};
use std::fmt::Write;

fn engine_name(e: Engine) -> &'static str {
    match e {
        Engine::Chrome => "Chrome",
        Engine::Firefox => "Firefox",
    }
}

fn counts_json(c: &StatusCounts) -> Value {
    json!({
        "total": c.total(), "implemented": c.implemented, "partial": c.partial, "delegated": c.delegated,
        "planned": c.planned, "unsupported": c.unsupported,
        "corePercent": round1(c.core_percent()), "withHostPercent": round1(c.with_host_percent()),
    })
}

fn round1(x: f64) -> f64 {
    (x * 10.0).round() / 10.0
}

/// Registry coverage as JSON, for CI dashboards.
pub fn registry_json(reg: &Registry) -> Value {
    let mut out = serde_json::Map::new();
    for engine in [Engine::Chrome, Engine::Firefox] {
        let by_ns: serde_json::Map<String, Value> =
            reg.counts_by_namespace(engine).into_iter().map(|(ns, c)| (ns, counts_json(&c))).collect();
        out.insert(engine_name(engine).to_lowercase(), json!({ "overall": counts_json(&reg.counts(engine)), "namespaces": by_ns }));
    }
    Value::Object(out)
}

/// The generated `docs/COVERAGE.md`. A test keeps the committed copy in sync with the registry.
pub fn registry_markdown(reg: &Registry) -> String {
    let mut s = String::new();
    s.push_str("# API coverage\n\n");
    s.push_str("<!-- GENERATED by `webext-coverage registry --markdown`. Do not edit; edit Data/api-support.json instead. -->\n\n");
    s.push_str("How much of the Chrome and Firefox extension API surface is covered. Numbers count API members (functions, events and properties) that the browser has, and come straight from `Data/api-support.json`.\n\n");
    s.push_str("- **core**: provided by this crate and covered by tests (`implemented` + `partial`).\n");
    s.push_str(
        "- **+host**: also counts `delegated` members, which the crate validates and routes but the embedding browser must implement.\n",
    );
    s.push_str("- **planned**: not available yet; calling it fails with a clear error.\n");
    s.push_str("- **Ladybird today**: core members that also work end to end in Ladybird. The rest of the core members need a browser-side primitive the integration does not have yet; they are listed under [Waiting for the browser](#waiting-for-the-browser).\n\n");
    s.push_str("| Browser | Members | core | +host | Ladybird today | planned |\n|---|---:|---:|---:|---:|---:|\n");
    for engine in [Engine::Chrome, Engine::Firefox] {
        let c = reg.counts(engine);
        let _ = writeln!(
            s,
            "| {} | {} | {:.1}% | {:.1}% | {:.1}% | {} |",
            engine_name(engine),
            c.total(),
            c.core_percent(),
            c.with_host_percent(),
            reg.working_in_browser(engine) as f64 * 100.0 / c.total().max(1) as f64,
            c.planned + c.unsupported
        );
    }
    s.push_str("\n## By namespace\n\nEach cell is `core/+host/total` members available in that browser.\n\n| Namespace | Chrome | Firefox | Planned (Chrome) |\n|---|---:|---:|---:|\n");
    let chrome: std::collections::HashMap<_, _> = reg.counts_by_namespace(Engine::Chrome).into_iter().collect();
    let firefox: std::collections::HashMap<_, _> = reg.counts_by_namespace(Engine::Firefox).into_iter().collect();
    let mut names: Vec<&String> = reg.namespaces().iter().collect();
    names.sort();
    let cell = |c: Option<&StatusCounts>| match c {
        Some(c) => format!("{}/{}/{}", c.implemented + c.partial, c.implemented + c.partial + c.delegated, c.total()),
        None => "–".to_string(),
    };
    for ns in names {
        let planned = chrome.get(ns).map_or("–".to_string(), |c| (c.planned + c.unsupported).to_string());
        let _ = writeln!(s, "| `{ns}` | {} | {} | {planned} |", cell(chrome.get(ns)), cell(firefox.get(ns)));
    }
    s.push_str("\n## Waiting for the browser\n\nThe core provides these, but Ladybird does not have the browser-side part yet, so calling them fails or has no visible effect:\n\n");
    for (name, what) in reg.awaiting_browser() {
        let _ = writeln!(s, "- `{name}`: {what}");
    }
    s.push_str("\nStatus notes (partial members):\n\n");
    for m in reg.members().iter().filter(|m| m.status == crate::registry::Status::Partial) {
        if let Some(n) = &m.note {
            let _ = writeln!(s, "- `{}`: {n}", m.full_name);
        }
    }
    s
}

pub fn registry_text(reg: &Registry, engine: Option<Engine>) -> String {
    let mut s = String::new();
    let engines: Vec<Engine> = engine.map_or(vec![Engine::Chrome, Engine::Firefox], |e| vec![e]);
    for e in engines {
        let c = reg.counts(e);
        let _ = writeln!(
            s,
            "{}: {} members | implemented {} | partial {} | delegated {} | planned {} | unsupported {}",
            engine_name(e),
            c.total(),
            c.implemented,
            c.partial,
            c.delegated,
            c.planned,
            c.unsupported
        );
        let _ = writeln!(s, "  core {:.1}%   with host {:.1}%", c.core_percent(), c.with_host_percent());
        let mut rows = reg.counts_by_namespace(e);
        rows.sort_by(|a, b| b.1.total().cmp(&a.1.total()).then(a.0.cmp(&b.0)));
        let _ = writeln!(s, "  {:<24} {:>5} {:>5} {:>5} {:>5} {:>5}", "namespace", "impl", "part", "deleg", "plan", "total");
        for (ns, c) in rows {
            let _ = writeln!(
                s,
                "  {:<24} {:>5} {:>5} {:>5} {:>5} {:>5}",
                ns,
                c.implemented,
                c.partial,
                c.delegated,
                c.planned + c.unsupported,
                c.total()
            );
        }
        s.push('\n');
    }
    s
}

pub fn verdict_text(v: Verdict) -> &'static str {
    match v {
        Verdict::Ready => "READY (everything it uses is implemented in the core)",
        Verdict::NeedsHost => "NEEDS HOST (works once the browser implements the delegated calls)",
        Verdict::Blocked => "BLOCKED (uses APIs or features that are not supported yet)",
    }
}

pub fn report_text(name: &str, r: &Report) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "{name}");
    let _ = writeln!(s, "  verdict: {}", verdict_text(r.verdict));
    let _ = writeln!(
        s,
        "  core {:.0}%   with host {:.0}%   ({} distinct APIs/features)",
        r.core_percent,
        r.with_host_percent,
        r.apis.len() + r.features.len()
    );
    if !r.features.is_empty() {
        s.push_str("  manifest features:\n");
        for f in &r.features {
            let _ = writeln!(
                s,
                "    [{:<11}] {}{}",
                f.status.as_str(),
                f.name,
                if f.note.is_empty() { String::new() } else { format!(" - {}", f.note) }
            );
        }
    }
    if !r.apis.is_empty() {
        s.push_str("  APIs used:\n");
        let mut apis: Vec<_> = r.apis.iter().collect();
        apis.sort_by(|a, b| a.name.cmp(&b.name));
        for a in apis {
            let (tag, engines) = match &a.support {
                Support::Known(st) => {
                    (st.as_str().to_string(), format!("{}{}", if a.in_chrome { "C" } else { "-" }, if a.in_firefox { "F" } else { "-" }))
                }
                Support::UnknownMember => ("unknown".to_string(), "??".to_string()),
            };
            let _ = writeln!(s, "    [{tag:<11}] {engines} {} (x{})", a.name, a.occurrences);
        }
    }
    if !r.blockers.is_empty() {
        let _ = writeln!(s, "  blockers: {}", r.blockers.join(", "));
    }
    s
}

pub fn report_json(name: &str, r: &Report) -> Value {
    json!({
        "name": name,
        "verdict": format!("{:?}", r.verdict),
        "corePercent": round1(r.core_percent),
        "withHostPercent": round1(r.with_host_percent),
        "blockers": r.blockers,
        "counts": r.counts,
        "features": r.features.iter().map(|f| json!({"name": f.name, "status": f.status.as_str(), "note": f.note})).collect::<Vec<_>>(),
        "apis": r.apis.iter().map(|a| json!({
            "name": a.name,
            "status": match &a.support { Support::Known(s) => s.as_str(), Support::UnknownMember => "unknown" },
            "chrome": a.in_chrome, "firefox": a.in_firefox, "occurrences": a.occurrences, "files": a.files,
        })).collect::<Vec<_>>(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// docs/COVERAGE.md must match the registry exactly. Regenerate with:
    ///   cargo run -p webext-cli -- registry --markdown > docs/COVERAGE.md
    #[test]
    fn committed_coverage_doc_is_up_to_date() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/COVERAGE.md");
        let committed = std::fs::read_to_string(path).expect("docs/COVERAGE.md must exist");
        assert_eq!(committed, registry_markdown(&Registry::builtin()), "docs/COVERAGE.md is stale; regenerate it");
    }

    #[test]
    fn json_and_text_render() {
        let reg = Registry::builtin();
        let j = registry_json(&reg);
        assert!(j["chrome"]["overall"]["total"].as_u64().unwrap() > 300);
        assert!(j["firefox"]["namespaces"]["storage"]["implemented"].as_u64().unwrap() >= 10);
        let t = registry_text(&reg, Some(Engine::Firefox));
        assert!(t.contains("Firefox:") && !t.contains("Chrome:"));
    }
}
